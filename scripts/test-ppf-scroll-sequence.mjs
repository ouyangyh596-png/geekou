import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8')
const component = read('src/components/PPFLayerAnimation.jsx')
const css = read('src/styles.css') + read('src/polish.css')
const mobile = read('src/mobile.css')
for (const marker of ['ppf-sequence-sticky', 'requestAnimationFrame', 'prefers-reduced-motion', 'ResizeObserver', 'cancelAnimationFrame', 'ppf-film-layer', 'backgroundRef']) assert.ok(component.includes(marker), marker)
assert.match(css, /\.ppf-sequence-sticky\s*\{[^}]*position:sticky/)
assert.match(css, /\.ppf-film-diagram\s*\{[^}]*width:100%/)
assert.match(css, /\.ppf-sequence-background/)
assert.match(css, /radial-gradient/)
assert.match(css, /@media\s*\(prefers-reduced-motion:reduce\)/)
assert.match(component, /passive: true/)
assert.match(component, /resize\.disconnect\(\)/)
assert.match(component, /motion\.removeEventListener/)
assert.match(component, /ppf-sequence-copy--top/)
assert.match(component, /href="#category=ppf"/)
assert.doesNotMatch(mobile, /background:#fafbfc|background:none/)
console.log('Shared sticky layout, scroll-linked background, motion policy and lifecycle contracts PASS')
